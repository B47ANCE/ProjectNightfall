-- Selectable Nightfall preset. Vanilla balance follows the current Apocalypse
-- preset; the tables below pin the coordinated suite's preferred settings.
local function copy(value)
    if type(value) ~= "table" then return value end
    local result = {}
    for key, entry in pairs(value) do result[key] = copy(entry) end
    return result
end

